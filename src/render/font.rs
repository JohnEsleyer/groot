/// Embedded 8x16 bitmap font rasterizer for rendering 2D text into RGBA textures.
pub fn render_text_to_rgba(text: &str, color: [f32; 4]) -> (u32, u32, Vec<u8>) {
    if text.is_empty() {
        return (1, 1, vec![0, 0, 0, 0]);
    }

    let char_w = 8usize;
    let char_h = 16usize;
    let width = (text.len() * char_w).max(1);
    let height = char_h;
    let mut buf = vec![0u8; width * height * 4];

    let r = (color[0].clamp(0.0, 1.0) * 255.0) as u8;
    let g = (color[1].clamp(0.0, 1.0) * 255.0) as u8;
    let b = (color[2].clamp(0.0, 1.0) * 255.0) as u8;
    let a = (color[3].clamp(0.0, 1.0) * 255.0) as u8;

    for (i, ch) in text.chars().enumerate() {
        let glyph = get_glyph_bitmap(ch);
        let x_offset = i * char_w;

        for row in 0..char_h {
            let row_byte = glyph[row];
            for col in 0..char_w {
                if (row_byte & (1 << (7 - col))) != 0 {
                    let px = x_offset + col;
                    let py = row;
                    let idx = (py * width + px) * 4;
                    buf[idx] = r;
                    buf[idx + 1] = g;
                    buf[idx + 2] = b;
                    buf[idx + 3] = a;
                }
            }
        }
    }

    (width as u32, height as u32, buf)
}

fn get_glyph_bitmap(ch: char) -> &'static [u8; 16] {
    let ascii = (ch as usize).clamp(0, 127);
    &FONT_8X16[ascii]
}

